import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '../..');
const blueprintsRoot = path.join(repoRoot, 'blueprints');
const outputPath = path.join(repoRoot, 'packages/mobile/src/generated/local-content.ts');
const isCheckMode = process.argv.includes('--check');

async function collectFiles(rootDir, predicate) {
  const entries = await fs.readdir(rootDir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = path.join(rootDir, entry.name);
      if (entry.isDirectory()) {
        return collectFiles(fullPath, predicate);
      }
      return predicate(fullPath) ? [fullPath] : [];
    }),
  );

  // Sort by repo-relative POSIX paths with a plain codepoint comparison:
  // `localeCompare` is locale/ICU-dependent and absolute paths differ by OS
  // separator (`\` vs `/`), so anything else can order files differently on
  // the CI runner than on the machine that committed the generated file —
  // failing `content:check` with no real drift. This ordering is identical
  // on every platform.
  return nested.flat().sort((left, right) => {
    const leftKey = toRepoRelative(left);
    const rightKey = toRepoRelative(right);
    return leftKey < rightKey ? -1 : leftKey > rightKey ? 1 : 0;
  });
}

function toRepoRelative(filePath) {
  return path.relative(repoRoot, filePath).replace(/\\/g, '/');
}

async function buildContentMap(files) {
  const pairs = await Promise.all(
    files.map(async (filePath) => {
      // Normalise at read time, before the content is stringified: CRLF inside
      // a JSON string becomes the literal escape text `\r\n`, which the check's
      // whole-file EOL normalisation cannot see. Without this, a Windows
      // checkout (CRLF on disk) and a Linux checkout (LF) produce different
      // generated files and CI fails with no real drift.
      const contents = (await fs.readFile(filePath, 'utf8')).replace(/\r\n/g, '\n');
      return [toRepoRelative(filePath), contents];
    }),
  );

  return Object.fromEntries(pairs);
}

const blueprintFiles = await collectFiles(blueprintsRoot, (filePath) => filePath.endsWith('.md'));
const templateManifestFiles = await collectFiles(path.join(blueprintsRoot, 'templates'), (filePath) =>
  filePath.endsWith('template.toml'),
);

const blueprintContents = await buildContentMap(blueprintFiles);
const templateManifestContents = await buildContentMap(templateManifestFiles);

const generated = `// Generated by tools/generation/generate-mobile-local-content.mjs
// Do not edit manually.

export const bundledBlueprintContents = ${JSON.stringify(blueprintContents, null, 2)} as const;

export const bundledTemplateManifestContents = ${JSON.stringify(templateManifestContents, null, 2)} as const;
`;

await fs.mkdir(path.dirname(outputPath), { recursive: true });

if (isCheckMode) {
  /**
   * Comparison normalises line endings: blueprint files are CRLF on Windows and
   * LF on a Linux checkout, and without this the check would fail on CI purely
   * because of the host. Real drift — edited blueprints, new files, deleted
   * files — still shows up.
   */
  const normalizeEol = (text) => text.replace(/\r\n/g, '\n');
  let existing = null;

  try {
    existing = await fs.readFile(outputPath, 'utf8');
  } catch {
    throw new Error(`${toRepoRelative(outputPath)} is missing. Run \`pnpm content:generate\` and commit the result.`);
  }

  if (normalizeEol(existing) !== normalizeEol(generated)) {
    throw new Error(
      `${toRepoRelative(outputPath)} is out of date with the files under blueprints/. Run \`pnpm content:generate\` and commit the result.`,
    );
  }

  console.log(
    `Mobile content check passed: ${Object.keys(blueprintContents).length} blueprint files and ${Object.keys(templateManifestContents).length} template manifests are in sync.`,
  );
} else {
  await fs.writeFile(outputPath, generated, 'utf8');

  console.log(
    `Wrote ${Object.keys(blueprintContents).length} blueprint files and ${Object.keys(templateManifestContents).length} template manifests to ${toRepoRelative(outputPath)}`,
  );
}
