import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '../..');
const outputPath = path.join(repoRoot, 'packages/shared/src/generated/legal-documents.ts');

/**
 * Repository documents that both the web app and the mobile app must render
 * from a single source. Web reads these through Vite's `?raw` import; mobile
 * cannot, so they are embedded here for both surfaces to consume.
 */
const SOURCES = [
  { file: 'LICENSE', exportName: 'licenseDocumentText', label: 'LICENSE' },
  { file: 'SECURITY.md', exportName: 'securityDocumentText', label: 'SECURITY.md' },
  { file: 'CODE_OF_CONDUCT.md', exportName: 'codeOfConductDocumentText', label: 'CODE_OF_CONDUCT.md' },
];

const isCheckMode = process.argv.includes('--check');

/**
 * Line endings are normalised to `\n` so the generated file is identical on
 * every platform: git checks these documents out with the host's line endings,
 * and an unormalised copy would make `--check` fail on CI for no real reason.
 */
function normalizeNewlines(contents) {
  return contents.replace(/\r\n?/g, '\n');
}

function toRepoRelative(filePath) {
  return path.relative(repoRoot, filePath).split(path.sep).join('/');
}

async function buildGeneratedSource() {
  const blocks = await Promise.all(
    SOURCES.map(async ({ file, exportName, label }) => {
      const contents = normalizeNewlines(await fs.readFile(path.join(repoRoot, file), 'utf8'));

      if (!contents.trim()) {
        throw new Error(`Refusing to embed an empty repository document: ${file}`);
      }

      if (contents.includes('`')) {
        throw new Error(
          `Cannot embed ${file} with a template literal because it contains a backtick. Escape it before generating.`,
        );
      }

      return `/** Verbatim contents of ${toRepoRelative(path.join(repoRoot, file))} (line endings normalised to LF). */\nexport const ${exportName} = \`${contents}\`;\n`;
    }),
  );

  return [
    '// Generated by tools/generation/generate-shared-info-documents.mjs',
    '// Do not edit manually.',
    '//',
    '// Source of truth: LICENSE, SECURITY.md and CODE_OF_CONDUCT.md in the repository root.',
    `// Regenerate with \`pnpm info:docs\`; CI runs \`pnpm info:docs:check\`.`,
    '',
    ...blocks,
  ].join('\n');
}

async function main() {
  const generated = await buildGeneratedSource();

  if (isCheckMode) {
    let existing = null;

    try {
      existing = await fs.readFile(outputPath, 'utf8');
    } catch {
      throw new Error(`${toRepoRelative(outputPath)} is missing. Run \`pnpm info:docs\` and commit the result.`);
    }

    if (existing !== generated) {
      throw new Error(
        `${toRepoRelative(outputPath)} is out of date with the repository documents. Run \`pnpm info:docs\` and commit the result.`,
      );
    }

    console.log(`Info document check passed: ${SOURCES.length} repository document(s) are in sync.`);
    return;
  }

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, generated, 'utf8');

  console.log(`Wrote ${SOURCES.length} repository document(s) to ${toRepoRelative(outputPath)}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
